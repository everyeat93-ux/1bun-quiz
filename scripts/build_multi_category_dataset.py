# 2. Add multi-category knowledge questions with variations
SITUATIONS = [
    "오늘의 브레인 상식 퀴즈: ",
    "지식 루틴 챌린지: ",
    "하루 1분 상식 체크: ",
    "알아두면 쓸모 있는 지식: ",
    "당신은 알고 계셨나요? "
]

for cat_name, items in KNOWLEDGE_CATEGORIES.items():
    cat_target = 250
    item_idx = 0
    while len([q for q in all_quizzes if q["category"] == cat_name]) < cat_target:
        base = items[item_idx % len(items)]
        variation_idx = item_idx // len(items)
        
        # Decide Option A vs Option B
        correct_is_a = random.choice([True, False])
        if correct_is_a:
            opt_a = base["correct"]
            opt_b = base["wrong"]
            ans = "A"
        else:
            opt_a = base["wrong"]
            opt_b = base["correct"]
            ans = "B"
            
        q_text = base["q"].replace("{A}", opt_a).replace("{B}", opt_b)
        if variation_idx > 0 and variation_idx < len(SITUATIONS):
            prefix = SITUATIONS[variation_idx]
            if not q_text.startswith(prefix):
                q_text = f"{prefix}{q_text}"
                
        all_quizzes.append({
            "id": next_id,
            "category": cat_name,
            "question": q_text,
            "optionA": opt_a,
            "optionB": opt_b,
            "answer": ans,
            "explanation": base["exp"],
            "tip": base["tip"]
        })
        next_id += 1
        item_idx += 1

print(f"Total quizzes generated: {len(all_quizzes)}")
counts = {}
for q in all_quizzes:
    counts[q["category"]] = counts.get(q["category"], 0) + 1
for cat, count in counts.items():
    print(f"  - {cat}: {count} questions")

