life_quizzes = []

VAR_PREFIXES = [
    "",
    "☕ [생활 밀착 상식] ",
    "💡 [알아두면 유익한 살림 꿀팁] ",
    "🚑 [안전 & 응급처치 상식] ",
    "🌿 [친환경 분리수거 가이드] ",
    "🚗 [교통 & 운전 법규 상식] ",
    "🩺 [가족 건강 관리 상식] "
]

q_id = 1
while len(life_quizzes) < TARGET_COUNT:
    topic_idx = (q_id - 1) % len(LIFE_CORE_TOPICS)
    topic_data = LIFE_CORE_TOPICS[topic_idx]
    
    # Sentence variation
    sent_idx = ((q_id - 1) // len(LIFE_CORE_TOPICS)) % len(topic_data["sentences"])
    base_sent = topic_data["sentences"][sent_idx]
    
    correct_is_a = random.choice([True, False])
    if correct_is_a:
        opt_a = topic_data["correct"]
        opt_b = topic_data["wrong"]
        ans = "A"
    else:
        opt_a = topic_data["wrong"]
        opt_b = topic_data["correct"]
        ans = "B"
        
    formatted_q = base_sent.replace("{A}", opt_a).replace("{B}", opt_b)
    
    round_num = (q_id - 1) // (len(LIFE_CORE_TOPICS) * len(topic_data["sentences"]))
    prefix = VAR_PREFIXES[round_num % len(VAR_PREFIXES)]
    if prefix and not formatted_q.startswith(prefix):
        formatted_q = f"{prefix}{formatted_q}"
        
    life_quizzes.append({
        "id": q_id,
        "category": "생활·상식",
        "question": formatted_q,
        "optionA": opt_a,
        "optionB": opt_b,
        "answer": ans,
        "explanation": topic_data["exp"],
        "tip": topic_data["tip"]
    })
    q_id += 1

print(f"Generated {len(life_quizzes)} '생활·상식' quizzes successfully.")

