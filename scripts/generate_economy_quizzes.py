# Generate 2,000 unique questions for '시사·경제'
TARGET_COUNT = 2000
economy_quizzes = []

# Situational prefixes to provide rich diversity
VAR_PREFIXES = [
    "",
    "💡 [경제 상식 퀴즈] ",
    "📈 [직장인 재테크 꿀팁] ",
    "🌐 [글로벌 시사 브리핑] ",
    "💼 [비즈니스 교양 상식] ",
    "📊 [금융 이해력 테스트] ",
    "🏛️ [알아두면 유용한 시사 퀴즈] "
]

q_id = 1
while len(economy_quizzes) < TARGET_COUNT:
    topic_idx = (q_id - 1) % len(ECONOMY_CORE_TOPICS)
    topic_data = ECONOMY_CORE_TOPICS[topic_idx]
    
    # Pick sentence variation
    sent_idx = ((q_id - 1) // len(ECONOMY_CORE_TOPICS)) % len(topic_data["sentences"])
    base_sent = topic_data["sentences"][sent_idx]
    
    # Decide Option A or B randomly
    correct_is_a = random.choice([True, False])
    if correct_is_a:
        opt_a = topic_data["correct"]
        opt_b = topic_data["wrong"]
        ans = "A"
    else:
        opt_a = topic_data["wrong"]
        opt_b = topic_data["correct"]
        ans = "B"
        
    formatted_q = base_sent.replace("{A}", opt_a).replace("{B}", opt_b)
    
    # Add prefix variation on subsequent rounds
    round_num = (q_id - 1) // (len(ECONOMY_CORE_TOPICS) * len(topic_data["sentences"]))
    prefix = VAR_PREFIXES[round_num % len(VAR_PREFIXES)]
    if prefix and not formatted_q.startswith(prefix):
        formatted_q = f"{prefix}{formatted_q}"
        
    economy_quizzes.append({
        "id": q_id,
        "category": "시사·경제",
        "question": formatted_q,
        "optionA": opt_a,
        "optionB": opt_b,
        "answer": ans,
        "explanation": topic_data["exp"],
        "tip": topic_data["tip"]
    })
    q_id += 1

print(f"Generated {len(economy_quizzes)} '시사·경제' quizzes successfully.")

